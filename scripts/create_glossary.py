def generate_glossary():
    # Build per-language mappings: { "hi": { "ऋण": "loan", ... }, ... }
    by_language = {}
    langs = ["hi", "ta", "te", "mr", "bn", "gu", "kn", "ml", "pa", "ur", "en"]
    for lang in langs:
        by_language[lang] = {}

    for eng_term, lang_map in TERMS.items():
        for lang, words in lang_map.items():
            if lang not in by_language:
                by_language[lang] = {}
            for w in words:
                clean_w = w.strip().lower()
                if clean_w:
                    by_language[lang][clean_w] = eng_term

    output = {
        "_metadata": {
            "title": "Nivara Multilingual Intent Terms Glossary",
            "version": "1.0.0",
            "supported_languages": langs,
            "total_terms": len(TERMS),
            "description": "Offline cross-language query normalization mapping Indic terms to English retrieval tokens."
        },
        "terms": TERMS,
        "by_language": by_language
    }

    with open(GLOSSARY_FILE, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    print(f"Glossary successfully generated at {GLOSSARY_FILE} with {len(TERMS)} canonical terms across {len(langs)} languages.")

if __name__ == "__main__":
    generate_glossary()
